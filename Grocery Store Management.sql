-- 3. Sales and Order Trends
-- Analyze business performance through orders and revenue over time.

-- ●	Q1. How many orders have been placed in total?

		SELECT COUNT(*) AS total_orders FROM orders;

-- ●	Q2. What is the average value per order?

		SELECT SUM(total_price) / COUNT(DISTINCT ord_id) AS avg_order_value
        FROM order_details;

-- ●	Q3. On which dates were the most orders placed?

		SELECT order_date, COUNT(ord_id) AS orders_count
        FROM orders
        GROUP BY order_date
        ORDER BY orders_count DESC
        LIMIT 5;

-- ●	Q4. What are the monthly trends in order volume and revenue?

		SELECT 
        LEFT (o.order_date, 7) AS order_month,
        COUNT(DISTINCT o.ord_id) AS order_volume,
        SUM(od.total_price) AS total_revenue
        FROM orders o
        JOIN order_details od ON o.ord_id = od.ord_id
        GROUP BY order_month
        ORDER BY order_month;

-- ●	Q5. How do order patterns vary across weekdays and weekends?
		
		SET SQL_SAFE_UPDATES = 0;

        ALTER TABLE orders ADD COLUMN date_converted DATE;

        UPDATE orders SET date_converted = STR_TO_DATE(order_date, '%m/%d/%Y');

        SELECT DayName(STR_TO_DATE(order_date, "%m/%d/%y")) AS weekday, 
        MonthName(STR_TO_DATE(order_date, "%m/%d/%y")) AS month_, 
        COUNT(ord_id) AS totalorders
        FROM orders
        GROUP BY weekday, month_
        ORDER BY weekday, month_;

        
