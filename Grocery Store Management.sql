-- 2. Product Performance
-- Evaluate how well products are performing in terms of sales and revenue.

-- ●	Q1. How many products exist in each category?

		SELECT c.cat_id, c.cat_name, 
		COUNT(p.prod_id) AS total_products
        FROM categories c
        LEFT JOIN products p ON c.cat_id = p.cat_id
        GROUP BY c.cat_id;

-- ●	Q2. What is the average price of products by category?

		SELECT c.cat_id, c.cat_name, 
        AVG(p.price) AS avg_price
        FROM categories c
        LEFT JOIN products p ON c.cat_id = p.cat_id
        GROUP BY c.cat_id;
        
-- ●	Q3. Which products have the highest total sales volume (by quantity)?

		SELECT p.prod_name, SUM(quantity) AS high_sales
        FROM order_details o 
        LEFT JOIN products p ON o.prod_id = p.prod_id
        GROUP BY prod_name
        ORDER BY high_sales DESC
        LIMIT 1;

-- ●	Q4. What is the total revenue generated by each product?

		SELECT SUM(o.total_price) AS total_revenue, p.prod_name
        FROM order_details o 
        LEFT JOIN products p ON o.prod_id = p.prod_id
        GROUP BY prod_name;

-- ●	Q5. How do product sales vary by category and supplier?

		SELECT c.cat_name, s.sup_name, 
        SUM(o.total_price) AS total_sales
        FROM order_details o
        JOIN products p ON o.prod_id = p.prod_id
        JOIN categories c ON p.cat_id = c.cat_id
        JOIN supplier s ON p.sup_id = s.sup_id
        GROUP BY c.cat_name, s.sup_name
        ORDER BY c.cat_name, total_sales DESC;

