-- 5️. Employee Performance
-- Assess how employees are handling and influencing sales.

-- ●	Q1. How many employees have processed orders?

		SELECT COUNT(DISTINCT emp_id) FROM orders;

-- ●	Q2. Which employees have handled the most orders?

		SELECT e.emp_id, e.emp_name, 
        COUNT(o.ord_id) AS ordered_most
        FROM orders o 
        JOIN employees e ON o.emp_id = e.emp_id
        GROUP BY e.emp_id
        ORDER BY ordered_most DESC
        LIMIT 1;

-- ●	Q3. What is the total sales value processed by each employee?

		SELECT e.emp_id, e.emp_name, 
        SUM(od.total_price) AS total_sales
        FROM employees e
        JOIN orders o ON e.emp_id = o.emp_id
        JOIN order_details od ON o.ord_id = od.ord_id
        GROUP BY e.emp_id
        ORDER BY total_sales DESC;
        

-- ●	Q4. What is the average order value handled per employee?

		SELECT e.emp_id, e.emp_name, 
        SUM(od.total_price) / COUNT(DISTINCT o.ord_id) AS avg_value
        FROM employees e
        JOIN orders o ON e.emp_id = o.emp_id
        JOIN order_details od ON o.ord_id = od.ord_id
        GROUP BY e.emp_id
        ORDER BY avg_value DESC;

