-- Analysis Questions
-- 1️. Customer Insights

-- ●	Q1. How many unique customers have placed orders?

		SELECT COUNT(DISTINCT cust_id) AS Unique_Customers 
        FROM Orders;

-- ●	Q2. Which customers have placed the highest number of orders?

		SELECT
			c.cust_id,
			c.cust_name,
			COUNT(o.ord_id) AS Orders_Count
		FROM Customers c
		JOIN Orders o ON c.cust_id = o.cust_id
		GROUP BY c.cust_id, c.cust_name
		ORDER BY Orders_Count DESC
		LIMIT 1; 

-- ●	Q3. What is the total and average purchase value per customer?

		SELECT 
			o.cust_id, 
            c.cust_name, 
            COUNT(DISTINCT o.ord_id) AS Num_Orders,
            SUM(od.total_price) AS total_purchase, 
            AVG(od.total_price) AS avg_purchase
		FROM orders o 
        JOIN order_details od ON o.ord_id = od.ord_id 
        JOIN customers c ON o.cust_id = c.cust_id
        GROUP BY o.cust_id, c.cust_name
        ORDER BY total_purchase DESC;
  
-- ●	Q4. Who are the top 5 customers by total purchase amount?
		
        SELECT o.cust_id, 
			c.cust_name, 
			SUM(od.total_price) AS Total_Purchase
		FROM orders o 
        JOIN order_details od ON o.ord_id = od.ord_id 
        JOIN customers c ON o.cust_id = c.cust_id
        GROUP BY o.cust_id
        ORDER BY total_purchase DESC
        LIMIT 5;
        
