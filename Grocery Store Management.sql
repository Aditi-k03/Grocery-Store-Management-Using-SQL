		SELECT * FROM supplier;
        SELECT COUNT(*) FROM supplier;

-- ●	Q2. Which supplier provides the most products?

		SELECT s.sup_id, s.sup_name, 
        COUNT(p.prod_id) AS product_count
        FROM supplier s 
        JOIN products p ON s.sup_id = p.sup_id
        GROUP BY s.sup_id
        ORDER BY product_count DESC;

-- ●	Q3. What is the average price of products from each supplier?

		SELECT s.sup_id, s.sup_name, 
        AVG(p.price) AS average_price_supplier
        FROM products p 
        JOIN supplier s ON s.sup_id = p.sup_id
        GROUP BY s.sup_id 
        ORDER BY average_price_supplier;

-- ●	Q4. Which suppliers contribute the most to total product sales (by revenue)?

		SELECT s.sup_id, s.sup_name, 
        SUM(od.total_price) AS total_revenue
        FROM supplier s
        JOIN products p ON s.sup_id = p.sup_id
        JOIN order_details od ON p.prod_id = od.prod_id
        GROUP BY s.sup_id
        ORDER BY total_revenue DESC;

